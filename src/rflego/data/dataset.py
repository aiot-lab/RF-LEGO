"""Dataset implementations for RF-LEGO Frequency Transform, Beamformer, and Detector."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import torch

from rflego.data.base import BaseDataset
from rflego.data.generator import (
    generate_beamformer_batch,
    generate_detector_batch,
    generate_frequency_transform_batch,
    make_rng,
)

__all__ = [
    "BaseDataset",
    "FrequencyTransformDataset",
    "BeamformerDataset",
    "DetectorDataset",
    "create_dataset",
]


class FrequencyTransformDataset(BaseDataset):
    """Dataset for RF-LEGO Frequency Transform training and evaluation.

    Supports either loading .pkl files generated by FtDataGenerator via data_dir,
    or generating n deterministic samples in memory.
    """

    def __init__(
        self,
        data_dir: str | Path | int | None = None,
        *,
        n: int | None = None,
        seed: int = 42,
        split: str = "train",
        N: int = 256,
        **kwargs: Any,
    ) -> None:
        if isinstance(data_dir, int) and n is None:
            n, data_dir = data_dir, None
        self.split = split
        if data_dir is not None:
            super().__init__(data_dir=data_dir)
        else:
            num_samples = 1024 if n is None else int(n)
            rng = make_rng("ft", seed)
            data = generate_frequency_transform_batch(num_samples, rng, N=N, **kwargs)
            super().__init__(data=data, n=num_samples)

    def __getitem__(self, idx: int) -> dict[str, Any]:
        if self.data_dir is not None:
            sample = self._load_pickle(idx)
            noise_signal = torch.as_tensor(sample["noisy_signal"], dtype=torch.cfloat).unsqueeze(0)
            clean_spectrum = torch.as_tensor(
                sample["clean_spectrum"], dtype=torch.cfloat
            ).unsqueeze(0)
            out: dict[str, Any] = {
                "input": noise_signal,
                "label": clean_spectrum,
                "x_real": noise_signal.real.squeeze(0),
                "x_imag": noise_signal.imag.squeeze(0),
                "target": clean_spectrum.abs().squeeze(0),
            }
            if sample.get("clean_signal") is not None:
                out["label_signal"] = torch.as_tensor(sample["clean_signal"], dtype=torch.cfloat)
            if sample.get("noisy_spectrum") is not None:
                out["input_fft"] = torch.as_tensor(sample["noisy_spectrum"], dtype=torch.cfloat)
            return out

        assert self.data is not None
        xr = torch.from_numpy(self.data["x_real"][idx])
        xi = torch.from_numpy(self.data["x_imag"][idx])
        target = torch.from_numpy(self.data["gt_spectrum"][idx])
        return {
            "input": torch.complex(xr, xi).unsqueeze(0),
            "label": target.to(torch.cfloat).unsqueeze(0),
            "x_real": xr,
            "x_imag": xi,
            "target": target,
            "gt_peak_bin": torch.tensor(self.data["gt_peak_bin"][idx]),
        }


class BeamformerDataset(BaseDataset):
    """Dataset for RF-LEGO Beamformer Direction-of-Arrival training and evaluation.

    Supports either loading .pkl files generated by BeamformerDataGenerator via data_dir,
    or generating n deterministic samples in memory.
    """

    def __init__(
        self,
        data_dir: str | Path | int | None = None,
        *,
        n: int | None = None,
        seed: int = 42,
        split: str = "train",
        M: int = 8,
        **kwargs: Any,
    ) -> None:
        if isinstance(data_dir, int) and n is None:
            n, data_dir = data_dir, None
        self.split = split
        if data_dir is not None:
            super().__init__(data_dir=data_dir)
        else:
            num_samples = 1024 if n is None else int(n)
            rng = make_rng("beamformer", seed)
            data = generate_beamformer_batch(num_samples, rng, M=M, **kwargs)
            super().__init__(data=data, n=num_samples)

    def __getitem__(self, idx: int) -> dict[str, Any]:
        if self.data_dir is not None:
            data_dict = self._load_pickle(idx)
            signal = data_dict["signal"]
            angle_spectrum = data_dict["angle_spectrum"]
            dictionary_info = data_dict["dictionary"]

            signal_tensor = (
                signal.clone().detach().to(torch.complex64)
                if isinstance(signal, torch.Tensor)
                else torch.as_tensor(signal, dtype=torch.complex64)
            ).squeeze(0)
            spectrum_tensor = (
                angle_spectrum.clone().detach().to(torch.complex64)
                if isinstance(angle_spectrum, torch.Tensor)
                else torch.as_tensor(angle_spectrum, dtype=torch.complex64)
            ).squeeze(0)

            steering = (
                dictionary_info["dictionary"]
                if isinstance(dictionary_info, dict) and "dictionary" in dictionary_info
                else dictionary_info
            )
            steering_tensor = torch.as_tensor(steering, dtype=torch.complex64)
            return {
                "input": signal_tensor,
                "label": spectrum_tensor,
                "dictionary": dictionary_info,
                "y": signal_tensor,
                "A": steering_tensor,
                "target": spectrum_tensor.abs(),
            }

        assert self.data is not None
        y = torch.from_numpy(self.data["y_meas"][idx])
        A = torch.from_numpy(self.data["A_dict"][idx])
        target = torch.from_numpy(self.data["gt_spectrum"][idx])
        return {
            "input": y,
            "label": target.to(torch.complex64),
            "dictionary": {"dictionary": A},
            "y": y,
            "A": A,
            "target": target,
            "gt_angle_idx": torch.from_numpy(self.data["gt_angle_idx"][idx]),
        }


class DetectorDataset(BaseDataset):
    """Dataset for RF-LEGO Detector peak-detection training and evaluation.

    Supports either loading .pkl files generated by DetectorDataGenerator via data_dir,
    or generating n deterministic samples in memory.
    """

    def __init__(
        self,
        data_dir: str | Path | int | None = None,
        *,
        n: int | None = None,
        seed: int = 42,
        split: str = "train",
        L: int = 128,
        **kwargs: Any,
    ) -> None:
        if isinstance(data_dir, int) and n is None:
            n, data_dir = data_dir, None
        self.split = split
        if data_dir is not None:
            super().__init__(data_dir=data_dir)
        else:
            num_samples = 1024 if n is None else int(n)
            rng = make_rng("detector", seed)
            data = generate_detector_batch(num_samples, rng, L=L, **kwargs)
            super().__init__(data=data, n=num_samples)

    def __getitem__(self, idx: int) -> dict[str, torch.Tensor]:
        if self.data_dir is not None:
            sample = self._load_pickle(idx)
            x = torch.as_tensor(sample["noisy_signal"], dtype=torch.float32)
            mask = torch.as_tensor(sample["labels"], dtype=torch.float32)
            return {
                "input": x.unsqueeze(0),
                "labels": mask,
                "x": x,
                "mask": mask,
            }

        assert self.data is not None
        x = torch.from_numpy(self.data["x"][:, idx])
        mask = torch.from_numpy(self.data["gt_mask"][:, idx])
        return {
            "input": x.unsqueeze(0),
            "labels": mask,
            "x": x,
            "mask": mask,
        }


_DATASETS: dict[str, type[BaseDataset]] = {
    "ft": FrequencyTransformDataset,
    "frequency_transform": FrequencyTransformDataset,
    "beamformer": BeamformerDataset,
    "detector": DetectorDataset,
}


def create_dataset(
    task: str,
    data_dir: str | Path | int | None = None,
    *,
    n: int | None = None,
    seed: int = 42,
    split: str = "train",
    **kwargs: Any,
) -> BaseDataset:
    """Factory function creating a task dataset from data_dir or in-memory synthesis."""
    key = task.lower()
    if key not in _DATASETS:
        raise ValueError(f"Unknown task {task!r}; expected one of {list(_DATASETS)}")
    if isinstance(data_dir, int) and n is None:
        n, data_dir = data_dir, None
    return _DATASETS[key](data_dir=data_dir, n=n, seed=seed, split=split, **kwargs)
